const DICTS: Record<string, Dict> = { es: ES, en: EN, ca: CA, de: DE, fr: FR, it: IT, pt: PT, nl: NL, ja: JA, zh: ZH };

/** An administration text: this dictionary first, then the older administration strings. */
export function a(key: string, vars?: Record<string, string | number>): string {
  const dict = DICTS[getLang()] || EN;
  let s = dict[key] ?? EN[key] ?? ES[key];
  if (s === undefined) return t2(key, vars);
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

const LOCALES: Record<string, string> = { es: "es-ES", en: "en-GB", ca: "ca-ES", de: "de-DE", fr: "fr-FR", it: "it-IT", pt: "pt-PT", nl: "nl-NL", ja: "ja-JP", zh: "zh-CN" };
const locale = () => LOCALES[getLang()] || "es-ES";

export function fmtDate(iso?: string | null): string {
  if (!iso) return "—";
  const d = new Date(iso);
  return Number.isNaN(d.getTime()) ? iso : d.toLocaleDateString(locale(), { day: "numeric", month: "short", year: "numeric" });
}

export function fmtDateTime(iso?: string | null): string {
  if (!iso) return "—";
  const d = new Date(iso);
  return Number.isNaN(d.getTime()) ? iso : d.toLocaleString(locale(), { day: "numeric", month: "short", year: "numeric", hour: "2-digit", minute: "2-digit" });
}

/** "5 min ago", "3 h ago", "2 d ago" and, past a month, the date. */
export function ago(iso?: string | null): string {
  if (!iso) return a("us_never");
  const ms = Date.now() - new Date(iso).getTime();
  if (Number.isNaN(ms)) return "—";
  const min = Math.floor(ms / 60000);
  if (min < 1) return a("ago_now");
  if (min < 60) return a("ago_min", { n: min });
  const h = Math.floor(min / 60);
  if (h < 24) return a("ago_h", { n: h });
  const d = Math.floor(h / 24);
  return d < 31 ? a("ago_d", { n: d }) : fmtDate(iso);
}

export function duration(seconds: number): string {
  const s = Math.max(0, Math.round(seconds || 0));
  const h = Math.floor(s / 3600);
  const m = Math.floor((s % 3600) / 60);
  return h ? `${h} h ${m} min` : m ? `${m} min` : `${s} s`;
}
